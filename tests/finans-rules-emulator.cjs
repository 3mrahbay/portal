// Local emulator only: FINANCE_RULES_FILE and FIRESTORE_EMULATOR_HOST required.
const {initializeTestEnvironment,assertSucceeds,assertFails}=require('@firebase/rules-unit-testing');
const fb=require('firebase/firestore');
const fs=require('node:fs');
const assert=require('node:assert/strict');
(async()=>{
 const endpoint=process.env.FIRESTORE_EMULATOR_HOST||'';
 if(!/^127\.0\.0\.1:\d+$/.test(endpoint)||!process.env.FINANCE_RULES_FILE)throw Error('Local emulator and candidate rules required.');
 const {bildirimOnayla,tahsilatiGeriAl}=await import('../js/finans/core.js');
 const [host,port]=endpoint.split(':');
 const env=await initializeTestEnvironment({projectId:'demo-finance-review',firestore:{host,port:Number(port),rules:fs.readFileSync(process.env.FINANCE_RULES_FILE,'utf8')}});
 let checks=0;
 const ok=async p=>{await assertSucceeds(p);checks++;},no=async p=>{await assertFails(p);checks++;};
 const db=name=>env.authenticatedContext(name,{email:name+'@example.test'}).firestore();
 const ref=(db,id)=>fb.doc(db,'odemeBildirimleri',id);
 const period=db=>fb.doc(db,'ogrenciler','child','donemler','2026-2027');
 const data={ogrenciId:'child',veliEmail:'veli@example.test',donem:'2026-2027',kalemTipi:'aidat-2026-09',tutar:400,bildirilenTutar:400,odemeTarihi:'2026-09-20',odemeYontemi:'havale',durum:'bekliyor'};
 try{
 await env.clearFirestore();
 await env.withSecurityRulesDisabled(async c=>{
 const d=c.firestore();
 for(const role of ['muhasebe','mudur','ogretmen','danisma','pdr'])await fb.setDoc(fb.doc(d,'personeller',role+'@example.test'),{rol:role,durum:'aktif'});
 await fb.setDoc(fb.doc(d,'veliler','veli@example.test'),{ogrenciIds:['child']});
 await fb.setDoc(fb.doc(d,'veliler','other@example.test'),{ogrenciIds:['otherChild']});
 await fb.setDoc(fb.doc(d,'ogrenciler','child'),{ogrenciAdSoyad:'Test Öğrenci'});
 await fb.setDoc(period(d),{aidatAyarlari:{baslangicAyi:'2026-09',taksitSayisi:2,aylikAidat:1000},aylikOdemeler:{}});
 });
 await ok(fb.setDoc(ref(db('veli'),'payment'),data));
 await ok(fb.getDoc(ref(db('veli'),'payment')));
 await ok(fb.getDocs(fb.query(fb.collection(db('veli'),'odemeBildirimleri'),fb.where('ogrenciId','==','child'),fb.where('veliEmail','==','veli@example.test'))));
 await no(fb.getDocs(fb.collection(db('veli'),'odemeBildirimleri')));
 await no(fb.getDoc(ref(db('other'),'payment')));
 await no(fb.setDoc(ref(db('other'),'forged'),{...data,veliEmail:'other@example.test'}));
 for(const patch of [{durum:'onaylandi'},{onaylayan:'Muhasebe'},{tahsilatIslendi:true},{tutar:0,bildirilenTutar:0},{donem:'bad'},{veliEmail:'other@example.test'}])await no(fb.setDoc(ref(db('veli'),'invalid'),{...data,...patch}));
 await no(fb.updateDoc(ref(db('veli'),'payment'),{durum:'onaylandi'}));
 await no(fb.updateDoc(period(db('veli')),{aylikOdemeler:{'2026-09':{odendi:true}}}));
 await no(fb.getDoc(ref(env.unauthenticatedContext().firestore(),'payment')));
 for(const role of ['ogretmen','danisma','pdr'])await no(fb.getDoc(ref(db(role),'payment')));
 const account=db('muhasebe');
 await ok(fb.getDoc(ref(account,'payment')));
 await ok(bildirimOnayla({fb,db:account,id:'payment',email:'muhasebe@example.test'}));
 const paid=(await fb.getDoc(period(db('veli')))).data();
 assert.equal(paid.aylikOdemeler['2026-09'].odenenTutar,400);checks++;
 assert.equal(paid.aylikOdemeler['2026-10'],undefined);checks++;
 assert.ok(!JSON.stringify(paid).includes('muhasebe@example.test'));checks++;
 await no(fb.getDoc(fb.doc(db('veli'),'odemeler','bildirim_payment')));
 await ok(fb.getDoc(fb.doc(account,'odemeler','bildirim_payment')));
 await assert.rejects(bildirimOnayla({fb,db:account,id:'payment',email:'muhasebe@example.test'}));checks++;
 await ok(fb.setDoc(ref(db('veli'),'remaining'),{...data,tutar:600,bildirilenTutar:600}));
 const attempts=await Promise.allSettled([1,2].map(()=>bildirimOnayla({fb,db:account,id:'remaining',email:'muhasebe@example.test'})));
 assert.equal(attempts.filter(r=>r.status==='fulfilled').length,1);checks++;
 assert.equal((await fb.getDoc(period(db('veli')))).data().aylikOdemeler['2026-09'].odenenTutar,1000);checks++;
 await ok(fb.setDoc(ref(db('veli'),'excess'),{...data,tutar:1,bildirilenTutar:1}));
 await assert.rejects(bildirimOnayla({fb,db:account,id:'excess',email:'muhasebe@example.test'}));checks++;
 assert.equal((await fb.getDoc(ref(account,'excess'))).data().durum,'bekliyor');checks++;
 await ok(bildirimOnayla({fb,db:account,id:'excess',email:'muhasebe@example.test',sonuc:'ret'}));
 assert.equal((await fb.getDoc(ref(db('veli'),'excess'))).data().durum,'reddedildi');checks++;
 const reverse={fb,db:account,id:'remaining',email:'muhasebe@example.test',tarih:'2026-09-21',neden:'Hatalı tahsilat onayını düzelt',tur:'duzeltme'};
 await no(tahsilatiGeriAl({...reverse,db:db('veli'),email:'veli@example.test'}));
 const reversals=await Promise.allSettled([1,2].map(()=>tahsilatiGeriAl(reverse)));
 assert.equal(reversals.filter(r=>r.status==='fulfilled').length,1);checks++;
 const reopened=(await fb.getDoc(period(db('veli')))).data();
 assert.equal(reopened.aylikOdemeler['2026-09'].odenenTutar,400);checks++;
 assert.equal(reopened.aylikOdemeler['2026-10'],undefined);checks++;
 assert.ok(!JSON.stringify(reopened).includes('Hatalı tahsilat'));checks++;
 await no(fb.getDoc(fb.doc(db('veli'),'odemeler','ters_remaining')));
 assert.equal((await fb.getDoc(ref(db('veli'),'remaining'))).data().durum,'geri_alindi');checks++;
 console.log(`PASS ${checks} finance emulator checks`);
 }finally{await env.cleanup();}
})().catch(e=>{console.error(e);process.exitCode=1;});
